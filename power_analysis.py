"""## 2. Binomial likelihood-ratio tests with Holm adjustment"""

# Vectorized across simulated experiments; arrays have shape (REPS,).
def binomial_loglik(x, n, p):
    p = np.clip(p, 1e-12, 1 - 1e-12)
    return x * np.log(p) + (n - x) * np.log1p(-p)

def pair_lrt_pvalue(x1, x2, n1, n2):
    x1 = np.asarray(x1, dtype=float)
    x2 = np.asarray(x2, dtype=float)
    p1, p2 = x1 / n1, x2 / n2
    pooled = (x1 + x2) / (n1 + n2)
    unrestricted = binomial_loglik(x1, n1, p1) + binomial_loglik(x2, n2, p2)
    restricted = binomial_loglik(x1, n1, pooled) + binomial_loglik(x2, n2, pooled)
    statistic = np.maximum(0, 2 * (unrestricted - restricted))
    return chi2.sf(statistic, df=1)

def holm_adjust(pvalues):
    """Three simultaneous tests; input shape (replicates, 3)."""
    pvalues = np.asarray(pvalues, dtype=float)
    order = np.argsort(pvalues, axis=1)
    ranked = np.take_along_axis(pvalues, order, axis=1)
    ranked_adj = np.maximum.accumulate(ranked * [3, 2, 1], axis=1)
    result = np.empty_like(pvalues)
    np.put_along_axis(result, order, np.minimum(ranked_adj, 1), axis=1)
    return result

def simulate(n, p_a, p_b, p_c, reps, rng):
    x_a = rng.binomial(n, p_a, size=reps)
    x_b = rng.binomial(n, p_b, size=reps)
    x_c = rng.binomial(n, p_c, size=reps)
    pvals = np.column_stack([
        pair_lrt_pvalue(x_a, x_b, n, n),
        pair_lrt_pvalue(x_a, x_c, n, n),
        pair_lrt_pvalue(x_b, x_c, n, n)
    ])
    reject = holm_adjust(pvals) < ALPHA
    return reject.mean(axis=0)  # P(reject AB), P(reject AC), P(reject BC)

# Sanity checks (both exact-null and pronounced alternative)
assert np.isclose(pair_lrt_pvalue([1], [1], 100, 100)[0], 1)
assert np.all(holm_adjust(np.array([[.001, .03, .2]])) <= 1)

"""## 3. Monte Carlo power curves and heatmap"""

# Intervention scenario: A's effect = delta, B's effect = 0, C = baseline.
# Accordingly AB and AC are false nulls, BC is true.
rng = np.random.default_rng(SEED)
n_grid = np.array([2500, 5000, 10000, 20000, 30000, 50000, 100000])
delta_grid = np.array([0.001, 0.0025, 0.005, 0.0075])
rows = []
for delta in delta_grid:
    for n in n_grid:
        assert p0 + delta < 1
        power_ab, power_ac, rejection_bc = simulate(n, p0 + delta, p0, p0, REPS, rng)
        rows.append(dict(n=int(n), delta=float(delta), power_AB=power_ab,
                         power_AC=power_ac, rejection_BC=rejection_bc))
power_df = pd.DataFrame(rows)
power_df.to_csv('power_results.csv', index=False)
print('\nPower results (head):\n', power_df.head().to_string(index=False))

fig, ax = plt.subplots(figsize=(6.8, 3.6))
for delta in delta_grid:
    sub = power_df[power_df['delta'] == delta]
    ax.plot(sub['n'], sub['power_AC'], 'o-', label=f'Lift = {100*delta:.2f} pp')
ax.axhline(0.8, ls='--', color='grey', lw=1, label='80% power')
ax.set(xlabel='Customers per group (A, B and C)', ylabel='Holm-adjusted power (A vs C)',
       title='Power versus sample size')
ax.set_ylim(0, 1.02)
ax.legend(fontsize=8, ncol=2)
ax.grid(alpha=.2)
fig.tight_layout()
fig.savefig('power_curves.pdf', bbox_inches='tight')
fig.savefig('power_curves.png', dpi=200, bbox_inches='tight')
plt.show()

mat = power_df.pivot(index='delta', columns='n', values='power_AC').loc[delta_grid, n_grid]
