"""## 4. Approximate sample size and simulation-based MDE"""

def sample_size_two_proportions(p_c, delta, target_power, alpha_pair):
    p_a = p_c + delta
    q = (p_a + p_c) / 2
    za = norm.ppf(1 - alpha_pair / 2)
    zb = norm.ppf(target_power)
    numer = (za * np.sqrt(2*q*(1-q)) +
             zb * np.sqrt(p_a*(1-p_a) + p_c*(1-p_c))) ** 2
    return int(np.ceil(numer / delta**2))

sizes = []
for delta in [0.0025, 0.005, 0.0075]:
    n80 = sample_size_two_proportions(p0, delta, 0.80, ALPHA / 3)
    n90 = sample_size_two_proportions(p0, delta, 0.90, ALPHA / 3)
    sizes.append(dict(delta_pp=100*delta, n_per_group_80=n80,
                      n_per_group_90=n90, total_3arms_80=3*n80))
size_df = pd.DataFrame(sizes)
size_df.to_csv('sample_size_results.csv', index=False)
print('\nConservative pairwise sample sizes (Bonferroni alpha=0.05/3):\n',
      size_df.to_string(index=False))

# Estimate MDE on a specified effect-size grid for the actual A/C arm size
# and a proposed future study, using the full Holm-adjusted procedure.
rng_mde = np.random.default_rng(SEED + 1)
mde_delta_grid = np.arange(0.00025, 0.01251, 0.00025)
mde_rows = []
for n in [actual_n, 50000]:
    curve = []
    for delta in mde_delta_grid:
        _, power_ac, _ = simulate(n, p0+delta, p0, p0, REPS, rng_mde)
        curve.append(power_ac)
    curve = np.array(curve)
    passing = np.flatnonzero(curve >= 0.80)
    mde = float(mde_delta_grid[passing[0]]) if len(passing) else np.nan
    mde_rows.append(dict(n_per_group=n, mde_pp=100*mde))
mde_df = pd.DataFrame(mde_rows)
mde_df.to_csv('mde_results.csv', index=False)
print('\nApproximate simulation MDE (80% power, 0.025 pp grid resolution):\n',
      mde_df.to_string(index=False))

